// ============================================================================
//  data/heroClassification.js — 英雄定位分類（Milestone I）
//
//  問題（Ray 回報）：圖鑑選「法師」只看得到 10 名。
//  查證結果：**圖鑑的過濾沒有壞**，是資料本身的分布——
//    坦克 15／戰士 20／刺客 20／**法師 10**／射手 20／輔助 15（合計 100，無缺漏）。
//  中路 20 名裡法師與刺客各 10，其中 `hundun`「混沌術士」名字就寫著術士、
//  五個技能全是混沌能量／爆炸／扭曲／吸收／換位，卻被標成刺客 —— 那是標錯。
//
//  ── 為什麼不直接把一堆人改成法師 ────────────────────────────────────────
//  任務單明講「優先修正資料分類與過濾，不要直接亂新增角色」。逐一檢視後，
//  真正**標錯**的只有兩名（見 ARCH_CORRECTIONS）。其餘像「冰霜守衛」
//  （護甲／壁壘／嘲諷）、「雷霆神射」（穿甲／射）雖然帶元素語彙，
//  但它們的**定位動詞**是坦克與射手，硬改成法師才是把資料改壞。
//
//  ── 解法：主定位 + 次要標籤 ──────────────────────────────────────────────
//  真實 MOBA 的英雄本來就會跨定位（法師刺客、坦克法師）。這裡保留**唯一主定位**
//  （`arch`，Milestone H 的行為層讀它，所以行為與公平性完全不受影響），
//  另外從**既有技能文字**推導次要標籤，讓圖鑑可以用「任一標籤符合」來過濾。
//
//  次要標籤採**嚴格證據**：該定位的專屬語彙命中 ≥ MIN_HITS 次，且沒有命中
//  互斥語彙。寬鬆規則實測會變成「法師 41、坦克 40」——每個人都是每個定位，
//  那等於沒有分類，不能算修好。
// ============================================================================

/**
 * 次要標籤需要的最少專屬語彙命中數。
 *
 * ⚠ 這個值是**量出來的**，不是猜的。實測（100 名英雄）：
 *     命中 ≥4 ⇒ 8 名有次要標籤；≥3 ⇒ 11 名；≥2 ⇒ **12 名**（含主定位修正後）。
 *   放寬到 2 之後各定位可見數為 坦15／戰21／刺21／法20／射20／輔15，仍然分得開；
 *   再往下放（例如只要命中 1 次）就會退化成「每個人都是每個定位」
 *   （早期實測：法師 41、坦克 40），那等於沒有分類。
 *   ⇒ 2 是「還撐得住證據」的下限。要讓更多英雄有第二定位，需要的是**更多資料**
 *   （例如英雄的實際數值或第二擅長位置欄位），不是再放寬門檻。
 */
const MIN_HITS = 2;

/**
 * 明確標錯的主定位修正（逐一列舉，附理由；不是批次改）。
 * 只有「名稱與五個技能都指向另一個定位」時才列進來。
 */
export const ARCH_CORRECTIONS = Object.freeze({
  //  名字就是「術士」，技能全為混沌法術，無任何兵器／潛行語彙。
  hundun: { from: "刺客", to: "法師", why: "名為術士且五技能皆為法術，無兵器或潛行語彙" },
  //  靈魂感知／打擊／護盾／鏈／佔據＝靈能法術，無近戰兵器。
  hunpo: { from: "戰士", to: "法師", why: "五技能皆為靈魂法術，無兵器語彙" },
});

/**
 * 各定位的**專屬**語彙（刻意避開泛用詞如「護盾」「能量」——它們每個定位都有，
 * 拿來當證據只會讓所有人變成所有定位）。
 */
const SIGNATURE = Object.freeze({
  法師: /術士|法師|先知|符文|咒|奧術|元素|預言|領域|結界|爆裂|洪流|風暴|冰霜|冰刃|冰晶|雷霆|雷鳴|烈焰|熔火|熔岩|星界|星光|虛空|混沌|時空|時間|引力|海嘯|靈魂|毒霧/g,
  刺客: /潛行|隱身|暗影|背刺|處決|斬殺|絕影|幻影|幻象|相位|穿越|突襲/g,
  坦克: /護甲|壁壘|嘲諷|格擋|堅壁|鎮守|吸收傷害|踐踏|盾牆|不動/g,
  戰士: /重擊|衝鋒|橫斬|連斬|狂暴|戰吼|劍氣|拳|爪擊|錘擊/g,
  射手: /穿甲|爆頭|連射|箭雨|狙擊|彈幕|射擊|齊射/g,
  輔助: /治療|庇護|護衛|淨化|鼓舞|加持|視野|復甦|增益/g,
});

/** 與某定位互斥的語彙（命中就不給該標籤）。 */
const CONFLICT = Object.freeze({
  法師: /斬|刀刃|劍|拳|爪|矛|錘|箭|狙|穿甲/,
  刺客: /嘲諷|壁壘|治療|庇護/,
  坦克: /潛行|隱身|狙|背刺/,
  戰士: /潛行|隱身|治療|庇護/,
  射手: /嘲諷|壁壘|潛行/,
  輔助: /處決|斬殺|背刺|狙擊/,
});

const skillText = (hero) => [hero?.P, hero?.Q, hero?.W, hero?.E, hero?.R].filter(Boolean).join(" ");

/** 套用主定位修正後的 arch（沒有修正 ⇒ 原值）。 */
export function correctedArch(hero) {
  const fix = ARCH_CORRECTIONS[hero?.id];
  if (fix && hero?.arch === fix.from) return fix.to;
  return hero?.arch ?? null;
}

/**
 * 英雄 → 定位標籤（第一個永遠是主定位）。
 * 純函式：只讀 `id / arch / P–R`，不改輸入、不碰任何 Store。
 */
export function heroTags(hero) {
  const primary = correctedArch(hero);
  if (!primary) return [];
  const text = skillText(hero);
  const tags = [primary];
  for (const [tag, rx] of Object.entries(SIGNATURE)) {
    if (tag === primary) continue;
    const hits = (text.match(rx) ?? []).length;
    if (hits < MIN_HITS) continue;
    if (CONFLICT[tag]?.test(text)) continue;
    tags.push(tag);
  }
  return tags;
}

/** 這名英雄是否屬於某定位（主或次要）——圖鑑過濾的唯一判準。 */
export const heroHasTag = (hero, tag) => heroTags(hero).includes(tag);

/** 統計用：{ 定位: 可見數 }（主 + 次要都算）。 */
export function tagCounts(heroes = []) {
  const out = {};
  for (const h of heroes) for (const t of heroTags(h)) out[t] = (out[t] ?? 0) + 1;
  return out;
}
