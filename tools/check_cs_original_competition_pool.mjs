import assert from 'node:assert/strict';
import {csOriginalMapIdentity,resolveCsMapIdentity} from '../src/battle/fps/csMapIdentity.js';
import {slimProfileRecord} from '../src/platform/persistence/saveSlim.js';
import {toCsMatchResult} from '../src/platform/contracts/CsMatchResult.js';
globalThis.localStorage={getItem:()=>null,setItem:()=>{},removeItem:()=>{}};
const {useProfileStore:store}=await import('../src/platform/profileStore.js');
const selection={schema:'CsMapSelection.v1',kind:'bo3',status:'resolved',mapOrder:['mirage','dust2','inferno']};
store.setState({matchmaking:{session:{mode:'cs',mapSelection:selection,series:{maps:[]},activeMatch:{phase:'map'}}}});
assert.equal(store.getState().optInCsOriginalCompetitionPool().ok,true);
assert.equal(store.getState().matchmaking.session.mapSelection.competitionPoolId,'original-v1');
const saved=JSON.parse(JSON.stringify(store.getState().matchmaking.session));
assert.equal(saved.mapSelection.competitionPoolId,'original-v1');
assert.deepEqual(slimProfileRecord({matchmaking:{session:saved}}).matchmaking.session.mapSelection,saved.mapSelection);
const ids=saved.mapSelection.mapOrder.map(key=>csOriginalMapIdentity(key).competitionMapId);
assert.equal(new Set(ids).size,3);
assert.equal(resolveCsMapIdentity({mapKey:'mirage',sceneVersion:'major.v3'}).competitionMapId,'confluence-station');
assert.equal(resolveCsMapIdentity({mapKey:'mirage'}).poolId,'legacy');
const raw={mode:'CS',id:'identity-contract-only',map:'mirage',sceneVersion:'major.v3',mapLayoutId:'esmo-confluence.v3.3',players:[],rounds:[]};
const result=toCsMatchResult(raw,{});
assert.equal(result.mapIdentity.competitionMapId,'confluence-station');
assert.equal(result.mapIdentity.layoutId,raw.mapLayoutId);
assert.equal(toCsMatchResult({...raw,sceneVersion:'major.v1'},{}).mapIdentity,undefined);
store.setState({matchmaking:{session:{...saved,series:{maps:[{mapKey:'mirage'}]}}}});
assert.equal(store.getState().optInCsOriginalCompetitionPool().ok,false);
store.setState({matchmaking:{session:{...saved,activeMatch:{phase:'battle'}}}});
assert.equal(store.getState().optInCsOriginalCompetitionPool().ok,false);
console.log('CS original competition pool boundary: 12/12 PASS (not full browser flow)');
